#!/usr/bin/env python3
"""Command line for the delivery pipeline control plane.

  python3 orchestration/run.py plan              what would run, in which parallel waves, and why (read-only)
  python3 orchestration/run.py run               run the stages, enforce gates and approvals, write the ledger
  python3 orchestration/run.py report            reliability metrics from the ledger -> orchestration/METRICS.md
  python3 orchestration/run.py verify            check the ledger's hash chain
  python3 orchestration/run.py graph             the stage graph as a Mermaid diagram

Exit codes (run): 0 success, 1 a stage failed, 2 blocked or awaiting a human, 3 aborted (policy violation, invalid pipeline or operator stop).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from engine import (  # noqa: E402
    Orchestrator,
    Pipeline,
    PipelineError,
    compute_metrics,
    read_events,
    render_metrics_md,
    verify_ledger,
)

HERE = Path(__file__).resolve().parent


def load(args) -> "tuple[Path, Pipeline]":
    root = Path(args.root).resolve() if args.root else HERE.parent
    pipeline = Pipeline.load(Path(args.pipeline) if args.pipeline else HERE / "pipeline.json")
    return root, pipeline


def cmd_plan(args) -> int:
    root, pipeline = load(args)
    orch = Orchestrator(root, pipeline, only=args.only)
    plan = orch.plan()
    stages = {s["id"]: s for s in plan["stages"]}
    print(f"Pipeline {pipeline.name}: {len(stages)} stages in {len(plan['waves'])} waves\n")
    for index, wave in enumerate(plan["waves"]):
        label = "  || ".join(wave)
        print(f"  wave {index}: {label}" + ("   (parallel)" if len(wave) > 1 else ""))
    print()
    print(f"  {'stage':<14}{'state':<12}{'autonomy':<13}{'depends on':<26}approvals")
    for sid, s in stages.items():
        appr = ", ".join(f"{k}:{v}" for k, v in s["approvals"].items())
        if s["release_gate"]:
            appr = (appr + " + " if appr else "") + "all upstream"
        appr = appr or "-"
        print(f"  {sid:<14}{s['state']:<12}{s['autonomy']:<13}{', '.join(s['depends_on']) or '-':<26}{appr}")
    bad = [p for p in plan["preflight"] if p[1] != "pass"]
    print("\nPolicy preflight:")
    for name, status, detail in plan["preflight"]:
        print(f"  [{'ok' if status == 'pass' else 'VIOLATION'}] {name}" + ("" if status == "pass" else f": {detail}"))
    return 3 if bad else 0


def cmd_run(args) -> int:
    root, pipeline = load(args)
    orch = Orchestrator(
        root,
        pipeline,
        workers=args.workers,
        keep_going=args.keep_going,
        rollback=args.rollback,
        tag_green=args.tag_green,
        only=args.only,
    )
    result = orch.run()
    print(f"\nledger: {orch.ledger.path.relative_to(root)}")
    if result.status in ("BLOCKED", "AWAITING_APPROVAL"):
        print("Needs a human or the environment: see the BLOCKED / AWAITING_APPROVAL lines above.")
    return result.exit_code


def cmd_report(args) -> int:
    root, pipeline = load(args)
    ledger_dir = root / "orchestration" / "ledger"
    events = read_events(ledger_dir)
    if not events:
        print("No runs recorded yet. Run: python3 orchestration/run.py run")
        return 0
    metrics = compute_metrics(events)
    body = render_metrics_md(metrics)
    print(body)
    if not args.no_write:
        out = root / "orchestration" / "METRICS.md"
        out.write_text(
            "# Pipeline reliability metrics\n\nGenerated by `python3 orchestration/run.py report` from the run ledger. "
            "Do not edit by hand.\n\n" + body,
            encoding="utf-8",
        )
        print(f"written: {out.relative_to(root)}")
    return 0


def cmd_verify(args) -> int:
    root, _ = load(args)
    problems = verify_ledger(root / "orchestration" / "ledger")
    if problems:
        print("LEDGER INTEGRITY PROBLEMS:")
        for p in problems:
            print("  " + p)
        return 1
    print("ledger ok: every run file is an unbroken hash chain")
    return 0


def cmd_graph(args) -> int:
    _, pipeline = load(args)
    print("flowchart LR")
    node = lambda sid: sid.replace("-", "_")  # noqa: E731  (hyphens are not safe in Mermaid ids)
    for sid, st in pipeline.stages.items():
        marker = " 🔒" if st.autonomy == "agent+human" else ""
        print(f'    {node(sid)}["{sid}{marker}"]')
    for sid, st in pipeline.stages.items():
        for dep in st.depends_on:
            print(f"    {node(dep)} --> {node(sid)}")
    return 0


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root", help="project root (default: the folder above orchestration/)")
    parser.add_argument("--pipeline", help="pipeline file (default: orchestration/pipeline.json)")
    sub = parser.add_subparsers(dest="command", required=True)

    p = sub.add_parser("plan", help="show waves, stage states and policy status; writes nothing")
    p.add_argument("--only", help="a stage and everything it depends on")
    p.set_defaults(fn=cmd_plan)

    p = sub.add_parser("run", help="run the pipeline")
    p.add_argument("--only", help="run one stage and everything it depends on")
    p.add_argument("--workers", type=int, help="parallel stages (default from the pipeline policy)")
    p.add_argument("--keep-going", action="store_true", help="after a failure keep running independent branches")
    p.add_argument("--rollback", action="store_true", help="execute a failed stage's rollback command (default: only record it)")
    p.add_argument("--tag-green", action="store_true", help="on full success, move the git tag pipeline/last-green here")
    p.set_defaults(fn=cmd_run)

    p = sub.add_parser("report", help="reliability metrics from the ledger")
    p.add_argument("--no-write", action="store_true", help="print only; do not write METRICS.md")
    p.set_defaults(fn=cmd_report)

    sub.add_parser("verify", help="verify ledger integrity").set_defaults(fn=cmd_verify)
    sub.add_parser("graph", help="print the stage graph as Mermaid").set_defaults(fn=cmd_graph)

    args = parser.parse_args(argv)
    try:
        return args.fn(args)
    except PipelineError as exc:
        print(f"invalid pipeline: {exc}", file=sys.stderr)
        return 3


if __name__ == "__main__":
    sys.exit(main())
